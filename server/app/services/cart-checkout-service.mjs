import crypto from"node:crypto";
import{landingHash}from"../landing/landing-contracts.mjs";
export class CartCheckoutError extends Error{constructor(code,status=400){super(code);
this.code=code;
this.status=status;
}}const fail=(c,s=400)=>{throw new CartCheckoutError(c,s)},plain=x=>x&&typeof x==="object"&&!Array.isArray(x),strict=(x,k)=>plain(x)&&Object.keys(x).every(y=>k.includes(y)),hash=x=>crypto.createHash("sha256").update(x).digest("hex"),token=()=>crypto.randomBytes(32).toString("base64url"),safeInt=x=>Number.isSafeInteger(x)&&x>=0,phone=x=>typeof x==="string"&&/^\+?[0-9۰-۹٠-٩ -]{7,24}$/.test(x),text=(x,n,nullable=false)=>nullable&&x===null||typeof x==="string"&&x.trim().length>0&&x.length<=n;

export function createCartCheckoutService({repository,shippingRegistry,now=()=>new Date()}){const at=()=>now(),iso=()=>at().toISOString(),plus=(h)=>new Date(at().getTime()+h*3600000).toISOString(),key=x=>{if(typeof x!=="string"||!x.trim()||x.length>200)fail("COMMERCE_IDEMPOTENCY_CONFLICT",409);
return x.trim();
},resolve=t=>{if(typeof t!=="string"||t.length<32||t.length>100)fail("CART_NOT_FOUND",404);
const c=repository.cartByTokenHash(hash(t));
if(!c)fail("CART_NOT_FOUND",404);
if(c.expiresAt<=iso()||c.status==="EXPIRED")fail("CART_EXPIRED",410);
if(c.status!=="ACTIVE")fail("CART_NOT_ACTIVE",409);
return c;
},resolveForOrder=t=>{if(typeof t!=="string"||t.length<32||t.length>100)fail("CART_NOT_FOUND",404);
const c=repository.cartByTokenHash(hash(t));
if(!c)fail("CART_NOT_FOUND",404);
if(c.expiresAt<=iso()||c.status==="EXPIRED")fail("CART_EXPIRED",410);
if(!["ACTIVE","CHECKED_OUT"].includes(c.status))fail("CART_NOT_ACTIVE",409);
return c;
},truth=(c,productId,variantId)=>{const p=repository.product(productId);
if(!p||p.workspaceId!==c.workspaceId||p.catalogId!==c.catalogId)fail("PRODUCT_NOT_PURCHASABLE",404);
if(p.status!=="ACTIVE"||!['IN_STOCK','PREORDER'].includes(p.availabilityStatus))fail("PRODUCT_NOT_PURCHASABLE",409);
let v=null;
if(variantId!==null){v=repository.variant(variantId);
if(!v||v.productId!==p.id||v.workspaceId!==c.workspaceId||v.status!=="ACTIVE"||!['IN_STOCK','PREORDER'].includes(v.availabilityStatus))fail("VARIANT_NOT_PURCHASABLE",409);
}const price=v?.priceOverride??p.basePrice,compare=v?.compareAtPriceOverride??p.compareAtPrice;
if(!safeInt(price)||p.currency!==c.currency)fail("CURRENCY_MISMATCH",409);
return{p,v,price,compare};
},lines=c=>{const current=repository.items(c.id);
if(!current.length)fail("CART_EMPTY",409);
return current.map(i=>{const t=truth(c,i.productId,i.variantId);
return{productId:t.p.id,variantId:t.v?.id||null,productName:t.p.name,variantTitle:t.v?.title||null,sku:t.v?.sku||null,variantAttributes:[],unitPrice:t.price,compareAtPrice:t.compare,quantity:i.quantity,lineTotal:t.price*i.quantity,assetId:t.p.primaryAssetId};
});
},totals=(ls,shipping=0)=>{const subtotal=ls.reduce((n,x)=>n+x.lineTotal,0);
if(!safeInt(subtotal)||!safeInt(shipping)||!safeInt(subtotal+shipping))fail("CHECKOUT_INVALID");
return{subtotal,shipping,discount:0,tax:0,grandTotal:subtotal+shipping};
};
return Object.freeze({
 createCart(input){if(!strict(input,["catalogId","customerScopeKey"])||typeof input.catalogId!=="string"||(input.customerScopeKey!==null&&typeof input.customerScopeKey!=="string"))fail("CART_ITEM_INVALID");
const c=repository.catalog(input.catalogId);
if(!c||c.status==="INACTIVE")fail("CATALOG_NOT_FOUND",404);
const raw=token(),value=repository.createCart({workspaceId:c.workspaceId,catalogId:c.id,tokenHash:hash(raw),scopeType:input.customerScopeKey?"AUTHENTICATED":"ANONYMOUS",scopeKey:input.customerScopeKey,currency:c.currency,now:iso(),expiresAt:plus(24*30)});
return{cart:value,cartToken:raw,items:[]};
},getCart(raw){const c=resolve(raw),ls=linesSafe(c),t=ls.length?totals(ls):{subtotal:0,shipping:0,discount:0,tax:0,grandTotal:0};
return{cart:c,items:repository.items(c.id),totals:t};
},addItem(raw,input){const c=resolve(raw);
if(!strict(input,["revision","productId","variantId","quantity","unitPrice","currency"])||!Number.isInteger(input.revision)||typeof input.productId!=="string"||(input.variantId!==null&&typeof input.variantId!=="string")||!Number.isInteger(input.quantity)||input.quantity<1||input.quantity>99||"unitPrice"in input||"currency"in input)fail("CART_ITEM_INVALID");
truth(c,input.productId,input.variantId);
const r=repository.addItem({cartId:c.id,revision:input.revision,productId:input.productId,variantId:input.variantId,quantity:input.quantity,now:iso()});
if(!r)fail("CART_REVISION_CONFLICT",409);
if(r.limit)fail("CART_ITEM_INVALID");
return{...r,totals:totals(lines(r.cart))};
},updateItem(raw,itemId,input){const c=resolve(raw);
if(!strict(input,["revision","quantity"])||!Number.isInteger(input.revision)||!Number.isInteger(input.quantity)||input.quantity<0||input.quantity>99)fail("CART_ITEM_INVALID");
const r=repository.updateItem({cartId:c.id,itemId,revision:input.revision,quantity:input.quantity,now:iso()});
if(!r)fail("CART_REVISION_CONFLICT",409);
if(r.missing)fail("CART_ITEM_INVALID",404);
return{...r,totals:r.items.length?totals(lines(r.cart)):{subtotal:0,shipping:0,discount:0,tax:0,grandTotal:0}};
},
 createCheckout(raw,input,rawKey){const c=resolve(raw);
if(!strict(input,["fulfillmentMode"])||!["PHYSICAL_DELIVERY","DIGITAL_OR_SERVICE","CONTACT_TO_COMPLETE"].includes(input.fulfillmentMode))fail("CHECKOUT_INVALID");
lines(c);
const normalized={cartId:c.id,mode:input.fulfillmentMode},r=repository.createCheckout({workspaceId:c.workspaceId,cartId:c.id,mode:input.fulfillmentMode,currency:c.currency,key:key(rawKey),requestHash:landingHash(normalized),now:iso(),expiresAt:plus(2)});
if(!r.created&&r.value.requestHash!==landingHash(normalized))fail("COMMERCE_IDEMPOTENCY_CONFLICT",409);
return{checkout:r.value,reusedResult:!r.created};
},updateCheckout(raw,checkoutId,input){const c=resolve(raw),ch=repository.checkout(checkoutId);
if(!ch||ch.cartId!==c.id)fail("CHECKOUT_INVALID",404);
if(ch.expiresAt<=iso())fail("CHECKOUT_EXPIRED",410);
const allowed=["revision","fulfillmentMode","shippingMethod","contactName","contactMobile","contactEmail","recipientName","recipientMobile","province","city","postalAddress","postalCode"];
if(!strict(input,allowed)||!Number.isInteger(input.revision)||!text(input.contactName,160)||!phone(input.contactMobile)||!text(input.contactEmail,254,true))fail("CHECKOUT_INVALID");
const method=shippingRegistry.get(input.shippingMethod);
if(!method||!method.modes.includes(input.fulfillmentMode)||input.fulfillmentMode!==ch.fulfillmentMode)fail("CHECKOUT_INVALID");
if(input.fulfillmentMode==="PHYSICAL_DELIVERY"&&(!text(input.recipientName,160)||!phone(input.recipientMobile)||!text(input.province,100)||!text(input.city,100)||!text(input.postalAddress,1000)||!text(input.postalCode,20,true)))fail("CHECKOUT_INVALID");
const ls=lines(c),t=totals(ls,method.amount),value=repository.updateCheckout({workspaceId:c.workspaceId,checkoutId:ch.id,revision:input.revision,mode:input.fulfillmentMode,shippingMethod:input.shippingMethod,contactName:input.contactName.trim(),contactMobile:input.contactMobile,contactEmail:input.contactEmail,recipientName:input.recipientName,recipientMobile:input.recipientMobile,province:input.province,city:input.city,address:input.postalAddress,postalCode:input.postalCode,...t,now:iso()});
if(!value)fail("CHECKOUT_REVISION_CONFLICT",409);
return{checkout:value};
},confirm(raw,checkoutId,input,rawKey){const c=resolveForOrder(raw),ch=repository.checkout(checkoutId);
if(!ch||ch.cartId!==c.id)fail("CHECKOUT_INVALID",404);
const k=key(rawKey),existing=repository.orderByCheckout(ch.id);
if(existing){if(existing.idempotencyKey!==k)fail("ORDER_ALREADY_CREATED",409);
return{pendingOrder:existing,reusedResult:true};
}if(ch.status!=="READY"||ch.expiresAt<=iso())fail("CHECKOUT_INVALID",409);
if(!strict(input,["revision"])||input.revision!==ch.revision)fail("CHECKOUT_REVISION_CONFLICT",409);
const ls=lines(c),method=shippingRegistry.get(ch.shippingMethod),t=totals(ls,method.amount),normalized={checkoutId:ch.id,revision:ch.revision,...t},r=repository.confirm({workspaceId:c.workspaceId,catalogId:c.catalogId,cartId:c.id,checkoutId:ch.id,publicRef:`LD-${crypto.randomBytes(9).toString("hex").toUpperCase()}`,contactName:ch.contactName,contactMobile:ch.contactMobile,contactEmail:ch.contactEmail,mode:ch.fulfillmentMode,shippingMethod:ch.shippingMethod,recipientName:ch.recipientName,recipientMobile:ch.recipientMobile,province:ch.province,city:ch.city,address:ch.postalAddress,postalCode:ch.postalCode,...t,currency:c.currency,key:k,requestHash:landingHash(normalized),items:ls,now:iso(),expiresAt:plus(24)});
return{pendingOrder:r.value,reusedResult:!r.created};
},getOrder(raw,ref){const c=repository.cartByTokenHash(hash(raw)),o=repository.order(ref);
if(!c||!o||o.cartId!==c.id)fail("ORDER_NOT_FOUND",404);
return{pendingOrder:o,items:repository.orderItems(o.id)};
},shipping(){return{version:shippingRegistry.version,methods:shippingRegistry.list()};
}});
function linesSafe(c){try{return lines(c);
}catch(e){if(e.code==="CART_EMPTY")return[];
throw e;
}}}
