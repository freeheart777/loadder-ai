export function buildContentTask({
  topic,
  contentType,
  typeTitle,
  goal,
  tone,
}) {
  const formats = {
    instagram:
      "یک کپشن اینستاگرام کوتاه با هوک، بدنه و CTA مناسب تولید کن.",
    reel:
      "یک سناریوی ریلز کوتاه شامل هوک، بدنه و CTA تولید کن.",
    blog:
      "یک متن کوتاه و ساختارمند برای مقاله یا بلاگ تولید کن.",
    banner:
      "یک تیتر تبلیغاتی قوی، زیرتیتر و CTA کوتاه تولید کن.",
    story:
      "یک مجموعه کوتاه استوری شامل هوک، پیام و CTA تولید کن.",
    sms:
      "یک پیامک کوتاه، واضح و فروش‌محور تولید کن.",
  };

  const formatInstruction =
    formats[contentType] ||
    "یک محتوای کوتاه و آماده انتشار تولید کن.";

  return {
    system: `
تو Content Agent پلتفرم Loadder هستی.

وظیفه تو تولید محتوای حرفه‌ای برای کسب‌وکارهاست.

قوانین:
- فقط فارسی روان و طبیعی بنویس.
- از ترجمه تحت‌اللفظی و عبارت‌های مصنوعی خودداری کن.
- از کلمات زبان‌های دیگر استفاده نکن مگر اصطلاح رایج تخصصی باشد.
- پاسخ نهایی باید مستقیماً قابل استفاده باشد.
- تحلیل و توضیح درباره نحوه فکر کردنت ننویس.
    `.trim(),

    user: `
نوع محتوا: ${typeTitle || contentType || "محتوای عمومی"}

موضوع:
${topic || ""}

هدف:
${goal || "افزایش تعامل"}

لحن:
${tone || "حرفه‌ای و صمیمی"}

دستور خروجی:
${formatInstruction}
    `.trim(),
  };
}
